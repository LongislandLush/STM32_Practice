/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */

  uint32_t reset_flags = RCC->CSR;

  /*
   * SRAM 剛上電時內容不保證為 0，
   * 所以使用 magic 判斷資料是否有效。
   */
  if (retained_data.magic != RETAIN_MAGIC)
  {
      retained_data.magic = RETAIN_MAGIC;
      retained_data.reset_count = 0U;
      retained_data.last_reset_flags = 0U;
  }

  retained_data.reset_count++;
  retained_data.last_reset_flags = reset_flags;

  /*
   * .bss 每次 Reset 前都會被 Startup Code 清零，
   * 因此它每次進入 main() 後都只會變成 1。
   */
  normal_bss_counter++;

  software_reset_seen =
      ((reset_flags & RCC_CSR_SFTRSTF) != 0U) ? 1U : 0U;

  /*
   * 清除 Reset Cause Flags，
   * 避免下一次讀到舊狀態。
   */
  __HAL_RCC_CLEAR_RESET_FLAGS();

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */

	  if (reset_requested != 0U)
	     {
	         reset_requested = 0U;

	         /*
	          * 簡易防彈跳，現在是在主程式而非 ISR。
	          */
	         HAL_Delay(100U);

	         /*
	          * 觸發 Cortex-M 系統重置。
	          */
	         NVIC_SystemReset();
	     }

  }
  /* USER CODE END 3 */
}

