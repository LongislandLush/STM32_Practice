  /* USER CODE BEGIN SysInit */

  uint32_t current_reset_csr = RCC->CSR;

  if (__HAL_RCC_GET_FLAG(RCC_FLAG_SFTRST) != RESET)
  {
      software_reset_detected = true;
  }

  /*
   * 第一次上電，或資料被破壞時重新初始化。
   */
  if (!NoInit_IsValid())
  {
      g_noinit_state.magic = NOINIT_MAGIC;
      g_noinit_state.warm_boot_count = 0U;
      g_noinit_state.previous_reset_csr = 0U;
  }

