static uint32_t NoInit_CalculateChecksum(
    uint32_t magic,
    uint32_t boot_count,
    uint32_t reset_csr)
{
    return magic ^
           boot_count ^
           reset_csr ^
           0xA5A55A5AUL;
}

static bool NoInit_IsValid(void)
{
    uint32_t expected =
        NoInit_CalculateChecksum(
            g_noinit_state.magic,
            g_noinit_state.warm_boot_count,
            g_noinit_state.previous_reset_csr);

    return (g_noinit_state.magic == NOINIT_MAGIC) &&
           (g_noinit_state.checksum == expected);
}

